const PLUGIN_OWNED = new Set(['grain', 'ir']);

describe('catalog coverage', () => {
  it('lists every ASL proto except grain and IR (plugin kinds)', () => {
    for (const proto of ASL_PROTOS) {
      const entry = catalogEntry(proto.kind);
      expect(entry, proto.kind).toBeDefined();
      expect(entry?.create, proto.kind).toBeTypeOf('function');
    }
    expect(grainMaterial.kind).toBe('grain');
    expect(irMaterial.kind).toBe('ir');
    expect(catalogEntry('grain')?.category).toBe('Plugins');
    expect(catalogEntry('ir')?.category).toBe('Plugins');
    expect(PLUGIN_OWNED.has('grain')).toBe(true);
  });

  it('has unique kinds and a Control section', () => {
    const kinds = catalog.map((entry) => entry.kind);
    expect(new Set(kinds).size).toBe(kinds.length);
    expect(categories()).toContain('Control');
    expect(categories()).toContain('Analysis');
    expect(catalogEntry('tuner')?.category).toBe('Analysis');
    expect(coreProtos).toHaveLength(ASL_PROTOS.length);
  });
});
