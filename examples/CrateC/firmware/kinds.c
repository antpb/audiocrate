/* Writes crate_embed_kinds.h for the patch in crate_embed.h: a constant
 * CRATE_KIND_ENABLED(k) over the node kinds that patch's plan uses, so a
 * firmware build compiles in only their evaluators (see compute() in
 * src/crate.c). Run on the host; pass the output with -include.
 *
 *   kinds > crate_embed_kinds.h
 */
#include <stdio.h>
#include "crate.h"
#include "crate_embed.h"

int main(void) {
    crate_plan plan;
    if (crate_plan_open(&plan, crate_embed_plan, sizeof crate_embed_plan) != 0) {
        fprintf(stderr, "kinds: the embedded plan does not open\n");
        return 1;
    }
    int used[CK_COUNT] = {0};
    for (int i = 0; i < plan.h->node_count; i++)
        if (plan.nodes[i].kind < CK_COUNT) used[plan.nodes[i].kind] = 1;
    printf("/* Generated by firmware/kinds.c from patch '%s'. Do not edit. */\n", CRATE_EMBED_ID);
    printf("#ifndef CRATE_EMBED_KINDS_H\n#define CRATE_EMBED_KINDS_H\n");
    printf("#define CRATE_KIND_ENABLED(k) (0");
    int n = 0;
    for (int k = 0; k < CK_COUNT; k++)
        if (used[k]) { printf(" || (k) == %d", k); n++; }
    printf(")\n/*");
    for (int k = 0; k < CK_COUNT; k++)
        if (used[k]) printf(" %s", crate_kind_names[k]);
    printf(" */\n#endif\n");
    fprintf(stderr, "kinds: %d of %d node kinds used by '%s'\n", n, (int)CK_COUNT, CRATE_EMBED_ID);
    return 0;
}
