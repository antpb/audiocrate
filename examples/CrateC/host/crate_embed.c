/*
 * crate_embed: one compiled patch into a C header a firmware links in.
 *
 * The pack format is for a device that holds the whole library in flash and
 * chooses between patches. A first hardware proof needs one patch, so this
 * emits a single plan blob as a byte array plus its parameter table (name,
 * range, CC address), skipping the pack container entirely. Same plan the
 * simulator and the pack use, built by crate_build_plan, so what the chip
 * renders is what the reference renders.
 *
 *   crate_embed factory-compiled.json <patch-id> out.h
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "crate_build.h"
#include "json.h"

int main(int argc, char **argv) {
    if (argc != 4) {
        fprintf(stderr, "usage: crate_embed factory-compiled.json <patch-id> out.h\n");
        return 2;
    }
    size_t len = 0;
    char *text = json_read_file(argv[1], &len);
    if (!text) { fprintf(stderr, "cannot read %s\n", argv[1]); return 2; }
    char err[256];
    json_value *doc = json_parse(text, len, err, sizeof err);
    free(text);
    if (!doc) { fprintf(stderr, "%s: %s\n", argv[1], err); return 2; }

    const json_value *patches = json_get(doc, "patches");
    const json_value *found = NULL;
    for (int i = 0; patches && i < patches->count; i++) {
        if (strcmp(json_string(json_get(&patches->items[i], "id"), ""), argv[2]) == 0) {
            found = &patches->items[i];
            break;
        }
    }
    if (!found) { fprintf(stderr, "no patch '%s'\n", argv[2]); return 2; }

    const json_value *compiled = json_get(found, "compiled");
    size_t blob_size = 0;
    void *blob = crate_build_plan(json_get(compiled, "graph"), &blob_size, err, sizeof err);
    if (!blob) { fprintf(stderr, "%s: %s\n", argv[2], err); return 1; }

    const char *role = json_string(json_get(compiled, "role"), "insert");
    const json_value *params = json_get(compiled, "params");

    FILE *f = fopen(argv[3], "w");
    if (!f) { fprintf(stderr, "cannot write %s\n", argv[3]); return 2; }
    fprintf(f, "/* Generated by crate_embed from patch '%s'. Do not edit. */\n", argv[2]);
    fprintf(f, "#ifndef CRATE_EMBED_H\n#define CRATE_EMBED_H\n#include <stdint.h>\n\n");
    fprintf(f, "#define CRATE_EMBED_ID \"%s\"\n", argv[2]);
    fprintf(f, "#define CRATE_EMBED_ROLE_INSTRUMENT %d\n", strcmp(role, "instrument") == 0 ? 1 : 0);
    fprintf(f, "\nstatic const uint8_t crate_embed_plan[%zu] = {\n", blob_size);
    const uint8_t *b = blob;
    for (size_t i = 0; i < blob_size; i++) {
        fprintf(f, "0x%02x,", b[i]);
        if ((i & 15) == 15) fputc('\n', f);
    }
    fprintf(f, "\n};\n\n");

    /* CC address -> default, so a firmware can seed and a CC can move it. */
    fprintf(f, "typedef struct { const char *name; float min, max, def; int16_t address; } crate_embed_param;\n");
    fprintf(f, "static const crate_embed_param crate_embed_params[] = {\n");
    int n = 0;
    for (int i = 0; params && params->type == JSON_OBJECT && i < params->count; i++) {
        const json_value *d = &params->items[i];
        fprintf(f, "  { \"%s\", %g, %g, %g, %d },\n", params->keys[i],
                json_number(json_get(d, "min"), 0), json_number(json_get(d, "max"), 1),
                json_number(json_get(d, "default"), 0),
                (int)json_number(json_get(d, "address"), -1));
        n++;
    }
    fprintf(f, "};\n#define CRATE_EMBED_PARAM_COUNT %d\n\n#endif\n", n);
    fclose(f);

    fprintf(stderr, "wrote %s: plan %zu bytes, %d params, role %s\n", argv[3], blob_size, n, role);
    free(blob);
    json_free(doc);
    return 0;
}
